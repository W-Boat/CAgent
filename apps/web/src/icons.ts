/**
 * 图标注册表。
 *
 * ── 为什么需要显式列出 ──
 *
 * 之前 main.ts 用 `import * as ElementPlusIconsVue` 把**全部 293 个图标**
 * 注册成全局组件，而项目实际只用到 77 个 —— 多出的 216 个白白进了首屏包。
 *
 * 之所以当初全量注册，是因为菜单/工具的图标名是**运行时字符串**
 * （模板里写的是 `<component :is="item.icon" />`），打包器无法静态分析，
 * 全量注册是最省事的做法。
 *
 * 但线上出口带宽实测只有约 1.49 MB/s（云服务商上限），首屏每 100KB gzip
 * 就多约 0.7 秒。因此这里改成**显式登记**：只 import 用得到的图标，
 * 体积显著下降；新增图标时在此处补一行即可，成本很低。
 *
 * 若忘记登记，图标会不显示（而不是报错），因此
 * `apps/api/scripts/check-icons.mjs` 会扫描源码里用到的图标名并核对本表。
 */
