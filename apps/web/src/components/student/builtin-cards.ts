/**
 * 学生端「固定内置卡片」。
 *
 * ── 为什么这些卡片不靠模型输出 ──
 *
 * 模型驱动的卡片有个改不掉的问题：**它不一定每次都输出**。
 * 同一个问题，这次给了漂亮的选项卡，下次可能只回一段文字。
 * 对多数卡片这可以接受（锦上添花），但对两类内容不行：
 *
 *   1. **心理求助入口** —— 这是安全兜底，必须每次都在、内容确定、号码确定。
 *      依赖模型「想起来」输出，等于把求助渠道建立在模型状态上。
 *   2. **校园高频办事入口** —— 入口固定，没必要每次让模型现编
 *      （它还可能编出不存在的入口）。
 *
 * 所以这里写成静态数据，在欢迎页直接渲染。
 * 求助卡（crisis）同时在消息流里可被模型触发 —— 两者互补：
 * 内置的保证「永远找得到」，模型触发的保证「说到这件事时立刻出现在眼前」。
 *
 * ── 内容纪律 ──
 *
 * 每条 action 都是「点击后代用户发给助手的话」，因此只写确实能回答的问题；
 * 号码只写已核实的官方号码。
 */

/** 内置卡片：一张卡 = 卡片协议里的一个 JSON 对象 */
export interface BuiltinCard {
  /** 稳定 id，用于 v-for 与渲染 key */
  id: string
  /** 分组标题，同组卡片渲染在同一区块下 */
  group: string
  /** 直接喂给 StudentCard 的卡片数据 */
  card: Record<string, unknown>
}

